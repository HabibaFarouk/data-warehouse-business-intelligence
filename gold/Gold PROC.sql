USE DATAWAREHOUSE;
GO

-- =====================================================================
-- Drop Procedure if it exists (Create from scratch, no ALTER)
-- =====================================================================
DROP PROCEDURE IF EXISTS GOLD.LOAD_GOLD;
GO

-- =====================================================================
-- Create Procedure
-- =====================================================================
CREATE PROCEDURE GOLD.LOAD_GOLD
AS
BEGIN
    SET NOCOUNT ON;

    -- Delete Children (Facts)
    DELETE FROM GOLD.FACT_STORE_SALES;
    DELETE FROM GOLD.FACT_ONLINE_SALES;

    -- Delete Parents (Dimensions)
    DELETE FROM GOLD.DIM_DATE;
    DELETE FROM GOLD.DIM_STORE;
    DELETE FROM GOLD.DIM_PRODUCT;
    DELETE FROM GOLD.DIM_CUSTOMER;
    DELETE FROM GOLD.DIM_EMPLOYEE;
    DELETE FROM GOLD.DIM_PROMOTION;
    DELETE FROM GOLD.DIM_WAREHOUSE;
    DELETE FROM GOLD.DIM_ORDER_STATUS;
    DELETE FROM GOLD.DIM_PAYMENT_METHOD;

    INSERT INTO GOLD.DIM_DATE (FULL_DATE, DAY, MONTH, YEAR)
    SELECT DISTINCT CAST(TRANSACTION_TIME AS DATE), DAY(TRANSACTION_TIME), MONTH(TRANSACTION_TIME), YEAR(TRANSACTION_TIME)
    FROM SILVER.POS_TRANSACTIONS
    UNION
    SELECT DISTINCT CAST(ORDER_TIME AS DATE), DAY(ORDER_TIME), MONTH(ORDER_TIME), YEAR(ORDER_TIME)
    FROM SILVER.ONLINE_ORDERS;

    INSERT INTO GOLD.DIM_STORE (STORE_ID, STORE_NAME, CITY, STATE, REGION, OPENING_DATE)
    SELECT STORE_ID, STORE_NAME, CITY, STATE, REGION, OPENING_DATE FROM SILVER.STORES;

    INSERT INTO GOLD.DIM_PRODUCT (PRODUCT_ID, SKU, PRODUCT_NAME, PACKAGE_SIZE, BRAND_NAME, DEPARTMENT_NAME)
    SELECT P.PRODUCT_ID, P.SKU, P.PRODUCT_NAME, P.PACKAGE_SIZE, B.BRAND_NAME, D.DEPARTMENT_NAME
    FROM SILVER.PRODUCTS P
    LEFT JOIN SILVER.BRANDS B ON P.BRAND_ID = B.BRAND_ID
    LEFT JOIN SILVER.DEPARTMENTS D ON P.DEPARTMENT_ID = D.DEPARTMENT_ID;

    INSERT INTO GOLD.DIM_CUSTOMER (CUSTOMER_ID, FULL_NAME, CITY, LOYALTY_LEVEL, EMAIL)
    SELECT CUSTOMER_ID, FULL_NAME, CITY, LOYALTY_LEVEL, EMAIL FROM SILVER.CUSTOMERS;

    INSERT INTO GOLD.DIM_EMPLOYEE (EMPLOYEE_ID, NAME, POSITION, HIRE_DATE)
    SELECT EMPLOYEE_ID, NAME, POSITION, HIRE_DATE FROM SILVER.EMPLOYEES;

    INSERT INTO GOLD.DIM_PROMOTION (PROMOTION_ID, PROMO_TYPE, DISCOUNT_PERCENT, START_DATE, END_DATE)
    SELECT PROMOTION_ID, PROMO_TYPE, DISCOUNT_PERCENT, START_DATE, END_DATE FROM SILVER.PROMOTIONS;

    INSERT INTO GOLD.DIM_WAREHOUSE (WAREHOUSE_ID, WAREHOUSE_NAME, CITY, STATE)
    SELECT WAREHOUSE_ID, WAREHOUSE_NAME, CITY, STATE FROM SILVER.WAREHOUSES;

    INSERT INTO GOLD.DIM_ORDER_STATUS (STATUS_NAME, DESCRIPTION)
    SELECT DISTINCT 
        TRIM(ORDER_STATUS),
        CASE 
            WHEN UPPER(TRIM(ORDER_STATUS)) = 'COMPLETED' THEN 'Order fulfilled and delivered successfully'
            WHEN UPPER(TRIM(ORDER_STATUS)) = 'PENDING' THEN 'Order placed, awaiting processing or payment'
            WHEN UPPER(TRIM(ORDER_STATUS)) = 'CANCELLED' THEN 'Order terminated by customer or system'
            ELSE 'Status: ' + TRIM(ORDER_STATUS)
        END
    FROM SILVER.ONLINE_ORDERS
    WHERE ORDER_STATUS IS NOT NULL;

    INSERT INTO GOLD.DIM_PAYMENT_METHOD (METHOD_NAME, PROVIDER)
    SELECT DISTINCT 
        TRIM(PAYMENT_METHOD),
        CASE 
            WHEN UPPER(TRIM(PAYMENT_METHOD)) LIKE '%CARD%' THEN 'Bank/Credit Network'
            WHEN UPPER(TRIM(PAYMENT_METHOD)) LIKE '%PAYPAL%' THEN 'PayPal Holdings Inc.'
            WHEN UPPER(TRIM(PAYMENT_METHOD)) LIKE '%CASH%' THEN 'Offline/Cash on Delivery'
            ELSE 'Third Party Provider'
        END
    FROM SILVER.PAYMENTS
    WHERE PAYMENT_METHOD IS NOT NULL;

    -- Load Fact_Store_Sales 
    INSERT INTO GOLD.FACT_STORE_SALES (DATE_KEY, STORE_KEY, PRODUCT_KEY, CUSTOMER_KEY, EMPLOYEE_KEY, PROMOTION_KEY, QUANTITY, UNIT_PRICE, SALES_AMOUNT)
    SELECT 
        D.DATE_KEY,
        S.STORE_KEY,
        P.PRODUCT_KEY,
        C.CUSTOMER_KEY,
        E.EMPLOYEE_KEY,
        PR.PROMOTION_KEY,
        TI.QUANTITY,
        TI.UNIT_PRICE,
        TI.TOTAL_LINE_AMOUNT
    FROM SILVER.TRANSACTION_ITEMS TI
    JOIN SILVER.POS_TRANSACTIONS PT ON TI.TRANSACTION_ID = PT.TRANSACTION_ID
    JOIN GOLD.DIM_DATE D      ON CAST(PT.TRANSACTION_TIME AS DATE) = D.FULL_DATE
    JOIN GOLD.DIM_STORE S     ON PT.STORE_ID = S.STORE_ID
    JOIN GOLD.DIM_PRODUCT P   ON TI.PRODUCT_ID = P.PRODUCT_ID
    JOIN GOLD.DIM_CUSTOMER C  ON PT.CUSTOMER_ID = C.CUSTOMER_ID
    JOIN GOLD.DIM_EMPLOYEE E  ON PT.EMPLOYEE_ID = E.EMPLOYEE_ID
    LEFT JOIN GOLD.DIM_PROMOTION PR ON TI.PROMOTION_ID = PR.PROMOTION_ID;

    -- Load Fact_Online_Sales
    INSERT INTO GOLD.FACT_ONLINE_SALES (
        DATE_KEY, CUSTOMER_KEY, PRODUCT_KEY, WAREHOUSE_KEY, 
        PROMOTION_KEY, ORDER_STATUS_KEY, PAYMENT_METHOD_KEY, 
        QUANTITY, UNIT_PRICE, SALES_AMOUNT
    )
    SELECT 
        D.DATE_KEY,
        C.CUSTOMER_KEY,
        P.PRODUCT_KEY,
        W.WAREHOUSE_KEY,
        PR.PROMOTION_KEY,
        OS.ORDER_STATUS_KEY,
        PM.PAYMENT_METHOD_KEY,
        OOI.QUANTITY,
        OOI.UNIT_PRICE,
        OOI.TOTAL_LINE_AMOUNT
    FROM SILVER.ONLINE_ORDER_ITEMS OOI
    JOIN SILVER.ONLINE_ORDERS OO ON OOI.ORDER_ID = OO.ORDER_ID
    LEFT JOIN SILVER.PAYMENTS PAY ON OO.ORDER_ID = PAY.ORDER_ID
    LEFT JOIN GOLD.DIM_DATE D ON CAST(OO.ORDER_TIME AS DATE) = D.FULL_DATE
    LEFT JOIN GOLD.DIM_CUSTOMER C ON OO.CUSTOMER_ID = C.CUSTOMER_ID
    LEFT JOIN GOLD.DIM_PRODUCT P ON OOI.PRODUCT_ID = P.PRODUCT_ID
    LEFT JOIN GOLD.DIM_WAREHOUSE W ON OO.WAREHOUSE_ID = W.WAREHOUSE_ID
    LEFT JOIN GOLD.DIM_PROMOTION PR ON OOI.PROMOTION_ID = PR.PROMOTION_ID
    LEFT JOIN GOLD.DIM_ORDER_STATUS OS ON OO.ORDER_STATUS = OS.STATUS_NAME
    LEFT JOIN GOLD.DIM_PAYMENT_METHOD PM ON PAY.PAYMENT_METHOD = PM.METHOD_NAME;

    PRINT '>> GOLD STAR SCHEMA (STORE AND ONLINE SALES) LOADED SUCCESSFULLY!';
END;
GO

EXEC GOLD.LOAD_GOLD;