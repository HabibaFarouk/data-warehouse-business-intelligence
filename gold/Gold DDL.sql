USE DATAWAREHOUSE;
GO

-- =====================================================================
-- 1. Create Gold Schema
-- =====================================================================
IF NOT EXISTS (SELECT * FROM sys.schemas WHERE name = 'GOLD') EXEC('CREATE SCHEMA GOLD');
GO

-- =====================================================================
-- 2. Drop Tables 
-- =====================================================================
DROP TABLE IF EXISTS GOLD.FACT_ONLINE_SALES;
DROP TABLE IF EXISTS GOLD.FACT_STORE_SALES;

DROP TABLE IF EXISTS GOLD.DIM_PAYMENT_METHOD;
DROP TABLE IF EXISTS GOLD.DIM_ORDER_STATUS;
DROP TABLE IF EXISTS GOLD.DIM_WAREHOUSE;
DROP TABLE IF EXISTS GOLD.DIM_PROMOTION;
DROP TABLE IF EXISTS GOLD.DIM_EMPLOYEE;
DROP TABLE IF EXISTS GOLD.DIM_CUSTOMER;
DROP TABLE IF EXISTS GOLD.DIM_PRODUCT;
DROP TABLE IF EXISTS GOLD.DIM_STORE;
DROP TABLE IF EXISTS GOLD.DIM_DATE;
GO

-- =====================================================================
-- 3. Create Dimension Tables
-- =====================================================================
CREATE TABLE GOLD.DIM_DATE (
    DATE_KEY    INT IDENTITY(1,1) PRIMARY KEY,
    FULL_DATE   DATE,
    DAY         INT,
    MONTH       INT,
    YEAR        INT
);

CREATE TABLE GOLD.DIM_STORE (
    STORE_KEY    INT IDENTITY(1,1) PRIMARY KEY,
    STORE_ID     INT,
    STORE_NAME   NVARCHAR(150),
    CITY         NVARCHAR(100),
    STATE        NVARCHAR(50),
    REGION       NVARCHAR(50),
    OPENING_DATE DATE
);

CREATE TABLE GOLD.DIM_PRODUCT (
    PRODUCT_KEY     INT IDENTITY(1,1) PRIMARY KEY,
    PRODUCT_ID      INT,
    SKU             NVARCHAR(100),
    PRODUCT_NAME    NVARCHAR(255),
    PACKAGE_SIZE    NVARCHAR(50),
    BRAND_NAME      NVARCHAR(100),
    DEPARTMENT_NAME NVARCHAR(100)
);

CREATE TABLE GOLD.DIM_CUSTOMER (
    CUSTOMER_KEY  INT IDENTITY(1,1) PRIMARY KEY,
    CUSTOMER_ID   INT,
    FULL_NAME     NVARCHAR(255),
    CITY          NVARCHAR(100),
    LOYALTY_LEVEL NVARCHAR(50),
    EMAIL         NVARCHAR(255)
);

CREATE TABLE GOLD.DIM_EMPLOYEE (
    EMPLOYEE_KEY INT IDENTITY(1,1) PRIMARY KEY,
    EMPLOYEE_ID  INT,
    NAME         NVARCHAR(200),
    POSITION     NVARCHAR(100),
    HIRE_DATE    DATE
);

CREATE TABLE GOLD.DIM_PROMOTION (
    PROMOTION_KEY    INT IDENTITY(1,1) PRIMARY KEY,
    PROMOTION_ID     INT,
    PROMO_TYPE       NVARCHAR(100),
    DISCOUNT_PERCENT DECIMAL(10,2),
    START_DATE       DATE,
    END_DATE         DATE
);

CREATE TABLE GOLD.DIM_WAREHOUSE (
    WAREHOUSE_KEY  INT IDENTITY(1,1) PRIMARY KEY,
    WAREHOUSE_ID   INT,
    WAREHOUSE_NAME NVARCHAR(150),
    CITY           NVARCHAR(100),
    STATE          NVARCHAR(50)
);

CREATE TABLE GOLD.DIM_ORDER_STATUS (
    ORDER_STATUS_KEY INT IDENTITY(1,1) PRIMARY KEY,
    STATUS_NAME      NVARCHAR(50),
    DESCRIPTION      NVARCHAR(255)
);

CREATE TABLE GOLD.DIM_PAYMENT_METHOD (
    PAYMENT_METHOD_KEY INT IDENTITY(1,1) PRIMARY KEY,
    METHOD_NAME        NVARCHAR(50),
    PROVIDER           NVARCHAR(100)
);
GO

-- =====================================================================
-- 4. Create Fact Tables (With Inline Foreign Keys)
-- =====================================================================
CREATE TABLE GOLD.FACT_STORE_SALES (
    SALES_ID      INT IDENTITY(1,1) PRIMARY KEY,
    DATE_KEY      INT FOREIGN KEY REFERENCES GOLD.DIM_DATE(DATE_KEY),
    STORE_KEY     INT FOREIGN KEY REFERENCES GOLD.DIM_STORE(STORE_KEY),
    PRODUCT_KEY   INT FOREIGN KEY REFERENCES GOLD.DIM_PRODUCT(PRODUCT_KEY),
    CUSTOMER_KEY  INT FOREIGN KEY REFERENCES GOLD.DIM_CUSTOMER(CUSTOMER_KEY),
    EMPLOYEE_KEY  INT FOREIGN KEY REFERENCES GOLD.DIM_EMPLOYEE(EMPLOYEE_KEY),
    PROMOTION_KEY INT FOREIGN KEY REFERENCES GOLD.DIM_PROMOTION(PROMOTION_KEY),
    QUANTITY      INT,
    UNIT_PRICE    DECIMAL(18,2),
    SALES_AMOUNT  DECIMAL(18,2)
);

CREATE TABLE GOLD.FACT_ONLINE_SALES (
    ONLINE_SALES_ID    INT IDENTITY(1,1) PRIMARY KEY,
    DATE_KEY           INT FOREIGN KEY REFERENCES GOLD.DIM_DATE(DATE_KEY),
    CUSTOMER_KEY       INT FOREIGN KEY REFERENCES GOLD.DIM_CUSTOMER(CUSTOMER_KEY),
    PRODUCT_KEY        INT FOREIGN KEY REFERENCES GOLD.DIM_PRODUCT(PRODUCT_KEY),
    WAREHOUSE_KEY      INT FOREIGN KEY REFERENCES GOLD.DIM_WAREHOUSE(WAREHOUSE_KEY),
    PROMOTION_KEY      INT FOREIGN KEY REFERENCES GOLD.DIM_PROMOTION(PROMOTION_KEY),
    ORDER_STATUS_KEY   INT FOREIGN KEY REFERENCES GOLD.DIM_ORDER_STATUS(ORDER_STATUS_KEY),
    PAYMENT_METHOD_KEY INT FOREIGN KEY REFERENCES GOLD.DIM_PAYMENT_METHOD(PAYMENT_METHOD_KEY),
    QUANTITY           INT,
    UNIT_PRICE         DECIMAL(18,2),
    SALES_AMOUNT       DECIMAL(18,2)
);
GO